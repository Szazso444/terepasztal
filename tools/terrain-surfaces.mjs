/** Package approved illustrated source surfaces for the cached runtime terrain painter. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { PNG } from 'pngjs';
import { resample } from './illustrated-sprites.mjs';
import { smoothPng } from './pixel-art.mjs';
const names = [
  'grass',
  'forest',
  'desert',
  'taiga',
  'swamp',
  'water',
  'sand',
  'rock',
  'city',
  'mountain',
];
// The opaque centre of each illustrated tile that `sampleSurface` reads, as x0, y0, x1, y1 of the
// source image. Must match SURFACE_WINDOW in src/render/terrainMaterials.ts.
const WINDOW = [0.25, 0.3, 0.75, 0.7];
const CELL = 512;

/**
 * Resamples one axis of `n` lines from [from, to) source pixels into `size` pixels: area average
 * when reducing, linear when enlarging, so the window keeps its native detail either way.
 */
function axis(src, length, lines, stride, step, from, to, size) {
  const out = new Float32Array(size * lines * 4),
    scale = (to - from) / size;
  for (let line = 0; line < lines; line++)
    for (let i = 0; i < size; i++)
      for (let c = 0; c < 4; c++) {
        let value = 0;
        if (scale > 1) {
          const a = from + i * scale,
            b = a + scale;
          for (let p = Math.floor(a); p < Math.ceil(b); p++)
            value +=
              src[(line * stride + Math.min(p, length - 1) * step) * 4 + c] *
              (Math.min(p + 1, b) - Math.max(p, a));
          value /= scale;
        } else {
          const t = from + (i + 0.5) * scale - 0.5,
            p = Math.max(0, Math.floor(t)),
            u = t - p,
            q = Math.min(p + 1, length - 1);
          value =
            src[(line * stride + p * step) * 4 + c] * (1 - u) +
            src[(line * stride + q * step) * 4 + c] * u;
        }
        out[(line * size + i) * 4 + c] = value;
      }
  return out;
}
function crop(src, [x0, y0, x1, y1]) {
  const rows = axis(
    src.data,
    src.width,
    src.height,
    src.width,
    1,
    x0 * src.width,
    x1 * src.width,
    CELL,
  );
  // `rows` is height lines of CELL pixels; resample each column across those lines.
  const columns = axis(rows, src.height, CELL, 1, CELL, y0 * src.height, y1 * src.height, CELL);
  const out = new PNG({ width: CELL, height: CELL });
  for (let x = 0; x < CELL; x++)
    for (let y = 0; y < CELL; y++)
      for (let c = 0; c < 4; c++)
        out.data[(y * CELL + x) * 4 + c] = Math.round(columns[(x * CELL + y) * 4 + c]);
  return out;
}

const sheet = new PNG({ width: CELL, height: CELL * names.length });
for (const [i, name] of names.entries()) {
  const rock = ['rock', 'mountain'].includes(name);
  const source = rock
    ? 'assets/source/terrain-production/rock-surface.png'
    : name === 'city'
      ? 'assets/source/base-v1/people-road-stone.png'
      : `assets/source/base-v1/terrain-${name}.png`;
  const png = PNG.sync.read(readFileSync(source));
  // Illustrated tiles are pixel art at about four source pixels per art pixel; smoothing at that
  // scale gives them the painted contours of the objects. Rock is already painted.
  const p = rock ? resample(png, CELL, CELL) : crop(smoothPng(png, 3), WINDOW);
  p.data.copy(sheet.data, i * CELL * CELL * 4);
}
mkdirSync('public/assets', { recursive: true });
writeFileSync('public/assets/terrain-surfaces.png', PNG.sync.write(sheet));
writeFileSync(
  'public/assets/terrain-surfaces.json',
  JSON.stringify(
    {
      version: 3,
      size: CELL,
      materials: names,
      window: WINDOW,
      source: ['assets/source/base-v1', 'assets/source/terrain-production/rock-surface.png'],
      purpose:
        'Approved illustrated texture samples; illustrated tiles are smoothed (pixel-art.mjs, radius 3) and keep the native-resolution centre window, rock the whole image. Generated by tools/terrain-surfaces.mjs',
    },
    null,
    2,
  ) + '\n',
);
console.log('Packed ten illustrated surface references.');
