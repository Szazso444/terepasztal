/**
 * Finishes the painted water and mountain swatches and packs them into the second surface sheet
 * of the landscape painter, `public/assets/wild-surfaces.png`. The ten ground cells of
 * `terrain-surfaces.png` stay as they are; the painter reads these by the material numbers after
 * them (`Material` in src/render/landscapeModel.ts).
 *
 * A painting is a return of the image tool, kept as it came. Finishing resamples it to a cell and
 * holds its highlights under the cap of the house rule (nothing painted is as bright as the cursor
 * or the selection), with a soft knee so the texture survives under the cap.
 *
 *   node tools/wild-surfaces.mjs          writes the sheet and its description
 *   node tools/wild-surfaces.mjs --check  fails on a wrong size, a pixel over its cap or any alpha
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';
import { resample } from './illustrated-sprites.mjs';

const WATER = 'assets/source/water-2026-10-11';
/** Water and foam stay under this (fall-geometry.json, `whiteMaximum`). */
const FOAM_CAP = [0xe0, 0xdd, 0xd2];

const CELLS = [
  { name: 'river', source: `${WATER}/river-water.png`, cap: FOAM_CAP },
  { name: 'bank', source: `${WATER}/river-bank.png`, cap: FOAM_CAP },
  { name: 'beach', source: `${WATER}/beach-sand.png`, cap: FOAM_CAP },
  { name: 'fall-lit', source: `${WATER}/fall-sheet-lit.png`, cap: FOAM_CAP },
  { name: 'fall-shade', source: `${WATER}/fall-sheet-shade.png`, cap: FOAM_CAP },
];
const CELL = 512;
const KNEE = 14;

/** `v` under `cap`, unchanged up to KNEE below it. */
function soft(v, cap) {
  const k = cap - KNEE;
  return v <= k ? v : k + KNEE * (1 - Math.exp(-(v - k) / KNEE));
}

/** The painting of `cell`, finished to a CELL x CELL picture. */
function finish(cell) {
  const p = resample(PNG.sync.read(readFileSync(cell.source)), CELL, CELL);
  for (let k = 0; k < p.data.length; k += 4) {
    for (let c = 0; c < 3; c++) p.data[k + c] = Math.round(soft(p.data[k + c], cell.cap[c]));
    p.data[k + 3] = 255;
  }
  return p;
}

const sheet = new PNG({ width: CELL, height: CELL * CELLS.length });
for (const [i, cell] of CELLS.entries()) finish(cell).data.copy(sheet.data, i * CELL * CELL * 4);

if (process.argv.includes('--check')) {
  const png = PNG.sync.read(readFileSync('public/assets/wild-surfaces.png'));
  const fail = (why) => {
    console.error(`wild-surfaces: ${why}`);
    process.exitCode = 1;
  };
  if (png.width !== CELL || png.height !== CELL * CELLS.length)
    fail(`${png.width} x ${png.height}, not ${CELL} x ${CELL * CELLS.length}`);
  for (const [i, cell] of CELLS.entries())
    for (let k = i * CELL * CELL * 4, n = 0; n < CELL * CELL; n++, k += 4) {
      if (png.data[k + 3] !== 255) {
        fail(`${cell.name} is not opaque`);
        break;
      }
      if ([0, 1, 2].some((c) => png.data[k + c] > cell.cap[c])) {
        fail(`${cell.name} is over its cap`);
        break;
      }
    }
  console.log(`Checked ${CELLS.length} cells.`);
} else {
  writeFileSync('public/assets/wild-surfaces.png', PNG.sync.write(sheet));
  writeFileSync(
    'public/assets/wild-surfaces.json',
    JSON.stringify(
      {
        size: CELL,
        materials: CELLS.map((c) => c.name),
        source: CELLS.map((c) => c.source),
        purpose:
          'Finished water and mountain swatches for the landscape painter, after the ten cells of terrain-surfaces.png. Generated by tools/wild-surfaces.mjs',
      },
      null,
      2,
    ) + '\n',
  );
  console.log(`Packed ${CELLS.length} wild surfaces.`);
}
