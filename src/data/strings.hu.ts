import type { Strings } from '../strings';

/**
 * The game in Hungarian: the table of `strings.ts`, key for key (`Strings` holds the two together).
 * The wording follows the UI workshop's mock: tile is csempe, Depot is Fűtőház, a store is a
 * készlet, and a hint is in the plain imperative (Kattints, Húzd). Numbers before a noun leave it
 * singular, so no plural is built here; a place in a sentence that would need a case ending on a
 * name goes after a colon instead, since a name cannot be declined from here.
 */
const AGE_NAMES: Record<string, string> = {
  steam: 'Gőzkorszak',
  diesel: 'Dízelkorszak',
  electric: 'Villamos korszak',
  nuclear: 'Atomkorszak',
  magnetic: 'Mágneses korszak',
  hyper: 'Hiperkorszak',
};
const AGE_IDS = ['steam', 'diesel', 'electric', 'nuclear', 'magnetic', 'hyper'];
function ageLabel(t: number) {
  return AGE_NAMES[AGE_IDS[t]] ?? `${t}. korszak`;
}
/** A whole number with its thousands apart, on one line. */
const grouped = (v: number) => Math.round(v).toLocaleString('en-US').replace(/,/g, '\u00a0');
const money = (v: number) => `${grouped(v)}\u00a0$`;
/** A number with a decimal comma. */
const dec = (v: number, digits = 2) => v.toFixed(digits).replace('.', ',');
/** A number as it is, with a decimal comma. */
const comma = (v: number) => String(v).replace('.', ',');

/** The ids the simulation and the editor hand a message: a terrain's and a deposit's. */
const GROUND: Record<string, string> = {
  grass: 'fű',
  forest: 'erdő',
  hill: 'domb',
  water: 'víz',
  rock: 'szikla',
  sand: 'homok',
  mountain: 'hegy',
};
const ground = (id: string) => GROUND[id.toLowerCase()] ?? id;
const DEPOSIT: Record<string, string> = { coal: 'szénér', oil: 'olajszivárgás' };
const deposit = (id: string) => DEPOSIT[id] ?? id;

